import os
from flask import Flask, render_template, request, jsonify
from dotenv import load_dotenv

load_dotenv()

app = Flask(__name__)

# Demo generator: lets you test the project even before connecting an AI API.
def demo_generate(content_type, topic, tone, length, audience):
    topic = topic.strip()
    tone = tone.lower()
    audience = audience.strip() or "general readers"

    if content_type == "Blog Post":
        return f"""# {topic}

## Introduction
Artificial intelligence and modern technology are changing the way people work, learn and solve problems. This article explores {topic.lower()} in a clear and practical way for {audience}.

## Key Ideas
One important consideration is how technology can make everyday tasks faster and more efficient. People can use digital tools to reduce repetitive work, organize information and focus on more valuable activities.

Another consideration is responsible use. Technology should support human decision-making rather than replace careful thinking. Users should check important information and understand the limitations of AI-generated content.

## Practical Example
A practical approach is to start with a small task, provide clear instructions, review the generated result and then improve the instructions based on what was missing.

## Conclusion
{topic} is an area where thoughtful use of technology can create useful opportunities. The best results come from combining AI tools with human judgment, creativity and review."""

    if content_type == "Social Media Post":
        return f"""🚀 Exploring {topic}

Technology is making it easier to create, learn and work smarter.

A useful approach is simple:
• Give AI clear instructions
• Review the result
• Improve the prompt
• Add your own ideas

The goal is not just to generate content — it is to create useful content with purpose.

#AI #Technology #ContentCreation"""

    if content_type == "Professional Email":
        return f"""Subject: Information Regarding {topic}

Dear [Name],

I hope you are well.

I am writing regarding {topic}. I would like to share some information and explore how we can move forward with this matter.

Please let me know if you require any additional information.

Kind regards,
[Your Name]"""

    if content_type == "Cover Letter":
        return f"""Dear Hiring Manager,

I am writing to express my interest in an opportunity related to {topic}.

I am a motivated software engineering student with an interest in technology, software development and artificial intelligence. I enjoy learning new technologies and applying what I learn to practical projects.

I would welcome the opportunity to contribute my skills while continuing to grow professionally.

Kind regards,
[Your Name]"""

    if content_type == "Study Notes":
        return f"""# Study Notes: {topic}

## 1. Definition
{topic} is a concept that can be understood by breaking it into its main ideas and practical applications.

## 2. Key Points
- Understand the basic definition.
- Learn the main components.
- Study practical examples.
- Test your understanding with questions.
- Review mistakes and improve.

## 3. Quick Review
Ask yourself:
1. What is {topic}?
2. Why is it important?
3. Where is it used?
4. Can I explain it in my own words?"""

    return f"""Content Topic: {topic}

Tone: {tone}
Audience: {audience}
Length: {length}

This is demo content generated by the Content Generator. Connect an AI provider in a later step for full generative AI output."""

@app.route("/")
def index():
    return render_template("index.html")

@app.post("/generate")
def generate():
    data = request.get_json() or {}
    required = ["content_type", "topic", "tone", "length"]
    if not all(data.get(key) for key in required):
        return jsonify({"error": "Please complete all required fields."}), 400

    content = demo_generate(
        data["content_type"],
        data["topic"],
        data["tone"],
        data["length"],
        data.get("audience", "")
    )
    return jsonify({"content": content, "mode": "demo"})

if __name__ == "__main__":
    app.run(debug=True)
